function fieldPolygon(
  lat: number,
  lng: number,
  halfWidth = 0.00032,
  halfHeight = 0.00022,
): GeoPoint[] {
  const point = (pointLat: number, pointLng: number): GeoPoint => ({
    lat: Number(pointLat.toFixed(6)),
    lng: Number(pointLng.toFixed(6)),
  });

  return [
    point(lat - halfHeight, lng - halfWidth),
    point(lat - halfHeight * 0.72, lng + halfWidth),
    point(lat + halfHeight, lng + halfWidth * 0.82),
    point(lat + halfHeight * 0.84, lng - halfWidth * 0.9),
    point(lat - halfHeight, lng - halfWidth),
  ];
}

